#!/usr/bin/env node
/**
 * `SCI-07R` service-topology acceptance (ADR-085), over HTTP, against a RUNNING estate:
 * the production BFF (COGNIX_WORLD_MODE=service) and a separate `cognix-world` process.
 *
 *   node scripts/sci07r-service-acceptance.mjs lifecycle
 *       curated unchanged; author → … → execute; refused; tenant isolation. Prints AUTHORED_ID=<id>.
 *   node scripts/sci07r-service-acceptance.mjs present <id>
 *       the authored scenario is listed and executes (run after a cognix-world restart).
 *   node scripts/sci07r-service-acceptance.mjs absent <id>
 *       the authored scenario is gone and the compiled catalogue is intact (run after a BFF restart —
 *       ADR-085 part 5: authored state is BFF-process-lifetime, `R-SCI07R-1`).
 *
 * BFF_URL defaults to http://127.0.0.1:3000 and WORLD_URL to http://127.0.0.1:8081.
 */
const BFF = process.env.BFF_URL || 'http://127.0.0.1:3000';
const WORLD = process.env.WORLD_URL || 'http://127.0.0.1:8081';
const TENANT = 'tenant_uk_retail_01';
const OTHER = 'tenant_sci07r_acceptance_other';
const COMPILED = ['SCN-FRESH-DAIRY-CHEDDAR-001', 'SCN-CHILLED-SALMON-002', 'SCN-BAKERY-SOURDOUGH-003'];

let passed = 0;
let failed = 0;
const assert = (ok, name, detail) => {
  if (ok) { console.log(`[PASS] ${name}`); passed++; }
  else { console.error(`[FAIL] ${name} — ${detail ?? 'assertion failed'}`); failed++; }
};
const call = async (path, init) => {
  const res = await fetch(path.startsWith('http') ? path : `${BFF}${path}`, init);
  let body = null;
  try { body = await res.json(); } catch { /* none */ }
  return { status: res.status, body };
};
const post = (path, body) => call(path, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
const catalogue = (tenant = TENANT) => call(`/api/v1/scenarios?tenant_id=${tenant}`);
const ids = c => (c.body?.data ?? []).map(e => e.scenario_id);
const q = (path, id, tenant = TENANT) => `${path}?scenario_id=${encodeURIComponent(id)}&tenant_id=${tenant}`;

async function author(inputs, tenant = TENANT) {
  const created = await post('/api/v1/scenarios/drafts', { tenant_id: tenant, situation: 'PROMOTION_DEMAND_SURGE', inputs });
  const draft = created.body?.data?.draft;
  const confirmed = await post(`/api/v1/scenarios/drafts/${draft.draft_id}/confirm`, { tenant_id: tenant, confirm: true, confirmed_by: 'Acceptance Operator' });
  return { created, draft, confirmed };
}

async function executes(id, label) {
  const decision = await call(q('/api/v1/scenarios/decision', id));
  assert(decision.status === 200 && decision.body?.data?.scenarioId === id, `${label}: decision evaluates under ${id}`);
  const signals = await call(q('/api/v1/signals', id));
  assert(signals.status === 200 && signals.body?.service === 'cognix-world' && signals.body?.scenario_id === id,
    `${label}: signals are generated BY cognix-world for ${id}`, JSON.stringify({ status: signals.status, service: signals.body?.service, message: signals.body?.message }));
  const current = await call(q('/api/v1/signals/current', id));
  assert(current.status === 200 && current.body?.service === 'cognix-world', `${label}: /signals/current reaches cognix-world (no fallback)`);
  return decision.body?.data;
}

async function lifecycle() {
  const opening = await catalogue();
  assert(opening.status === 200 && opening.body?.service === 'cognix-web-bff' && opening.body?.authority === 'scenario-runtime',
    'catalogue is published by the BFF scenario runtime in service mode');
  assert(JSON.stringify(ids(opening).slice(0, 3)) === JSON.stringify(COMPILED)
    && opening.body.data.slice(0, 3).every(e => e.certification_state === 'CERTIFIED'),
    'the three compiled scenarios, CERTIFIED, by canonical id');
  assert((await call(`${WORLD}/api/v1/scenarios`)).status === 410, 'cognix-world serves no catalogue (410)');
  for (const id of COMPILED) await executes(id, 'compiled');

  const a = await author({ sku_id: 'P004' });
  const id = a.draft?.scenario_id;
  assert(a.confirmed.status === 201 && a.confirmed.body?.data?.certified === true && a.confirmed.body?.data?.demo_active === false,
    'authored: resolve → certify → register → certify authoritatively → confirm; not activated by confirmation', id);
  const listed = await catalogue();
  const entry = listed.body.data.find(e => e.scenario_id === id);
  assert(!!entry && entry.certification_state === 'CERTIFIED', 'authored: APPEARS in the catalogue the selector renders (R-SCI07-6)');
  const record = await call(q('/api/v1/scenarios/record', id));
  assert(record.status === 200 && record.body?.data?.identity?.scenario_id === id, 'authored: certified record published for the browser projection');
  const selected = await post('/api/v1/scenarios', { scenario_id: id, tenant_id: TENANT });
  assert(selected.status === 200 && selected.body?.active_scenario_id === id, 'authored: selectable through the activation gate');
  const after = await catalogue();
  assert(after.body.active_scenario_id === id && after.body.data.find(e => e.scenario_id === id)?.demo_active === true,
    'authored: catalogue and active pointer agree (R-32)');
  const decision = await executes(id, 'authored');

  const r = await author({ ...(await refusedInputs()) });
  const rid = r.draft?.scenario_id;
  assert(r.confirmed.status === 422, 'refused: confirmation refused by the gate');
  assert(!ids(await catalogue()).includes(rid), 'refused: not in the catalogue');
  assert((await call(q('/api/v1/scenarios/record', rid))).status === 400, 'refused: record not published');
  assert((await post('/api/v1/scenarios', { scenario_id: rid, tenant_id: TENANT })).status === 422, 'refused: cannot be activated');
  assert((await call(q('/api/v1/signals', rid))).status === 400 && (await call(q('/api/v1/scenarios/decision', rid))).status === 400,
    'refused: cannot be executed');

  assert(!ids(await catalogue(OTHER)).includes(id), 'tenant: another tenant does not see it');
  assert((await call(q('/api/v1/scenarios/record', id, OTHER))).status === 400, 'tenant: cannot fetch its record');
  assert((await post('/api/v1/scenarios', { scenario_id: id, tenant_id: OTHER })).status === 422, 'tenant: cannot activate it');
  assert((await call(q('/api/v1/signals', id, OTHER))).status === 400 && (await call(q('/api/v1/scenarios/decision', id, OTHER))).status === 400,
    'tenant: cannot execute it');

  console.log(`AUTHORED_DECISION=${JSON.stringify(decision)}`);
  console.log(`AUTHORED_ID=${id}`);
}

async function refusedInputs() {
  // A coherent decision case the gate refuses at C-2.6 (one-percent participation) — `SCI-07`'s fixture.
  return {
    sku_id: 'P004', situation: 'PROMOTION_DEMAND_SURGE', market_scope: 'NATIONAL', focus_region: 'North West',
    channels: ['In store', 'Online'], scenario_name: 'Cheddar under a committed national cut',
    decision_question: 'Is the committed depth still right, and can we serve what it creates?',
    national_store_count: 1450, online_demand_share_pct: 14, base_demand_units_per_week: 350000,
    total_demand_movement_pct: 28.59, forecast_horizon_days: 14, promotion_duration_days: 14,
    promotion_depth_pct: 20, promotion_participation_pct: 1, gross_margin_rate_pct: 30,
    supplier_promotional_funding_pct: 35, promotional_response_pp_per_depth_point: 2.4,
    supplier_capacity_index: 1.1, supplier_flex_rate_pct: 12, flex_premium_rate_pct: 12,
    supplier_lead_time_days: 3, store_cover_days: 4, distribution_centre_cover_days: 6, on_order_cover_days: 8,
    observed_history_end_date: '2026-06-03', waste_units_per_week: 14700, cannibalisation_rate_pct: 8,
    substitution_recovery_pct: 35
  };
}

async function present(id) {
  assert(ids(await catalogue()).includes(id), `present: ${id} is still in the catalogue`);
  await executes(id, 'present');
}

async function absent(id) {
  const c = await catalogue();
  assert(!ids(c).includes(id), `absent: ${id} is gone after a BFF restart, as ADR-085 part 5 states`);
  assert(JSON.stringify(ids(c)) === JSON.stringify(COMPILED) && c.body.active_scenario_id === COMPILED[0],
    'absent: the compiled catalogue is intact and the reference scenario is active');
  assert((await call(q('/api/v1/scenarios/record', id))).status === 400
    && (await post('/api/v1/scenarios', { scenario_id: id, tenant_id: TENANT })).status === 422,
    'absent: nothing dangles — record and activation refuse it');
}

const [mode, arg] = process.argv.slice(2);
const task = mode === 'present' ? present(arg) : mode === 'absent' ? absent(arg) : lifecycle();
task.then(() => {
  console.log(`=== SCI-07R service acceptance (${mode || 'lifecycle'}): ${passed} passed, ${failed} failed ===`);
  process.exit(failed === 0 ? 0 : 1);
}).catch(error => { console.error('[FAIL] crashed —', error); process.exit(1); });
